/**
 * Seeded pseudo-random generator (mulberry32). The same seed gives the same
 * sequence on every platform, so a traffic seed replays exactly.
 */
export class Rng {
  private s: number;

  constructor(seed: number) {
    this.s = seed >>> 0;
  }

  /** Uniform in [0, 1). */
  next(): number {
    this.s = (this.s + 0x6d2b79f5) >>> 0;
    let t = this.s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  }

  /** Uniform in [a, b). */
  range(a: number, b: number): number {
    return a + (b - a) * this.next();
  }

  chance(p: number): boolean {
    return this.next() < p;
  }

  pick<T>(items: readonly T[]): T {
    return items[Math.min(items.length - 1, Math.floor(this.next() * items.length))];
  }
}

/** Normalise any number to a positive 31-bit seed (0 becomes 1). */
export function normaliseSeed(seed: number): number {
  const s = Math.abs(Math.trunc(seed)) % 2147483647;
  return s === 0 ? 1 : s;
}
