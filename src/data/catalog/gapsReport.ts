import { CATALOG, fullName, readinessOf } from '.';
import type { CatalogEntry } from './types';

/** Provenance rows that are still waiting for a confirmed source. */
function openEstimates(e: CatalogEntry): string[] {
  if (!e.sim) return [];
  return e.sim.provenance
    .filter((p) => p.status === 'estimated' && /awaiting spec sheet|Recalled published figure|not verified/i.test(p.source))
    .map((p) => `${p.parameter} (using ${p.value})`);
}

function sourceLinks(e: CatalogEntry): string {
  return e.sources
    .filter((s) => s.url)
    .slice(0, 3)
    .map((s) => `[${s.publisher}](${s.url})`)
    .join(' · ');
}

/**
 * Markdown list of every car's missing or unconfirmed data, for spec-sheet
 * follow-up. Generated into docs/DATA_GAPS.md by `npm run generate:gaps`.
 */
export function buildGapsReport(): string {
  const lines: string[] = [
    '<!-- GENERATED by `npm run generate:gaps` — do not edit by hand. -->',
    '# Data gaps and spec-sheet requests',
    '',
    'Every value the simulator could not confirm from a reachable source. A spec sheet (gear ratios,',
    'final drive, rated output with rpm, curb mass, tire size, Cd) for any car below lets it be',
    'confirmed or made playable. Sources already consulted are linked for each car.',
    '',
  ];
  const catalogOnly = CATALOG.filter((e) => readinessOf(e) === 'catalog');
  const playable = CATALOG.filter((e) => readinessOf(e) !== 'catalog' && !e.owner);

  lines.push(`## Catalog-only cars (${catalogOnly.length}) — need data before they can run`, '');
  for (const e of catalogOnly) {
    lines.push(`### ${fullName(e)}`, '', `- Why: ${e.unsupportedReason ?? 'Not modelled yet.'}`);
    lines.push(`- Missing: ${e.dataGaps.join('; ') || '—'}`);
    const links = sourceLinks(e);
    if (links) lines.push(`- Consulted: ${links}`);
    lines.push('');
  }

  lines.push(`## Playable cars (${playable.length}) — running on estimates to confirm`, '');
  for (const e of playable) {
    const est = openEstimates(e);
    const gaps = e.dataGaps;
    if (est.length === 0 && gaps.length === 0) continue;
    lines.push(`### ${fullName(e)}`, '');
    if (est.length) lines.push(`- Unconfirmed inputs: ${est.join('; ')}`);
    if (gaps.length) lines.push(`- Also missing: ${gaps.join('; ')}`);
    const links = sourceLinks(e);
    if (links) lines.push(`- Consulted: ${links}`);
    lines.push('');
  }
  return lines.join('\n');
}
